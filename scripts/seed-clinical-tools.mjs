#!/usr/bin/env node
/**
 * Turn the tool files in `packages/clinical-tools/src` into a seed migration.
 *
 * A tool this product ships is not a different kind of object from a tool a
 * customer pushes. It is a `tools` row and a `tool_versions` row, the version
 * holding the source and a `sha256:` checksum over it — the only difference is
 * `origin = 'vendor'`, which says the console may not edit it and may not
 * unlock it either.
 *
 * **The checksum and the type-stripping come from the CLI's own module**, not
 * from a copy written here. `packages/cli/src/project.ts` already owns what a
 * tool file must satisfy — one file, a default export, no relative imports —
 * and a second implementation of that is a second set of rules that will
 * disagree with the first. This project has recorded that fault three times:
 * the node catalogue snapshot, `CALL_FACTS` in the console, and the first
 * pre-flight, which it describes as "a cheaper imitation is a second
 * implementation that can disagree with the first".
 *
 * Usage:
 *   node scripts/seed-clinical-tools.mjs <NNNN> <slug>   # writes the migration
 *   node scripts/seed-clinical-tools.mjs --check         # source vs committed
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { stripTypeScriptTypes } from "node:module";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "packages/clinical-tools/src");

/** Same rule the CLI enforces: sha256 over the source as written, not the code. */
const checksum = (source) => `sha256:${createHash("sha256").update(source, "utf8").digest("hex")}`;

/** Same refusals as `checkSource`, so a file that cannot be pushed cannot be seeded. */
function check(source, file) {
    const relative = /\bfrom\s+["'](\.\.?\/[^"']+)["']/.exec(source);
    if (relative) throw new Error(`${basename(file)} imports "${relative[1]}" from a sibling — a tool ships as one file`);
    if (!/export\s+default\b/.test(source)) throw new Error(`${basename(file)} has no default export`);
}

/**
 * Read the definition without running the SDK.
 *
 * `defineTool` validates and compiles; here only the declared fields are
 * wanted, so it is replaced with identity. Importing the real SDK would drag
 * its module resolution into a script that runs before any install.
 */
async function load(file) {
    const source = readFileSync(file, "utf8");
    check(source, file);
    const shimmed = source.replace(/^import\s*\{[^}]*\}\s*from\s*["']@vokoo\/sdk["'];?\s*$/m, "const defineTool = (d) => d;");
    const js = stripTypeScriptTypes(shimmed, { mode: "strip" });
    const mod = await import("data:text/javascript," + encodeURIComponent(js));
    return { source, definition: mod.default };
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const files = readdirSync(SRC).filter((f) => f.endsWith(".ts")).sort().map((f) => join(SRC, f));
if (files.length === 0) throw new Error(`no tool files in ${SRC}`);

const tools = [];
for (const file of files) {
    const { source, definition: d } = await load(file);
    if (!d?.id || !d?.name) throw new Error(`${basename(file)} has no id or name`);
    tools.push({
        file: basename(file),
        id: d.id,
        name: d.name,
        description: d.description ?? "",
        // The compiled input schema is what the model is shown. Built here the
        // same way the SDK builds it, from the same `input` map.
        schema: compileInput(d.input ?? {}),
        timeout: d.timeoutSeconds ?? null,
        source,
        checksum: checksum(source),
    });
}

/** A minimal `compileSchema`: this seeds only tools whose inputs are scalars. */
function compileInput(input) {
    const properties = {};
    const required = [];
    for (const [name, f] of Object.entries(input)) {
        if (!["string", "number", "integer", "boolean"].includes(f.type)) {
            throw new Error(`input "${name}" is ${f.type}; the seeder handles scalars only so far`);
        }
        properties[name] = f.description ? { type: f.type, description: f.description } : { type: f.type };
        if (f.required) required.push(name);
    }
    return required.length ? { type: "object", properties, required } : { type: "object", properties };
}

const rows = tools
    .map(
        (t) =>
            `    (${q(t.id)}::uuid, ${q(t.name)}, ${q(t.description)}, ${q(JSON.stringify(t.schema))}::jsonb, ` +
            `${q(t.checksum)}, ${q(t.source)}, ${t.timeout ?? "null"})`,
    )
    .join(",\n");

const sql = `-- The clinical tools this product ships.
--
-- Ported from the copied implementations in \`vokoo-clinical-schemas/archive\` and
-- kept in \`packages/clinical-tools/src\`. Generated by
-- \`node scripts/seed-clinical-tools.mjs\` — the checksum and the file rules come
-- from the CLI's own module, so a file that could not be pushed cannot be
-- seeded either.
--
-- \`origin = 'vendor'\`: the console shows them and edits neither. Their
-- authority is this repository, and the next run of the generator would
-- overwrite anything typed into the console — which is the failure this
-- project already named as the worst shape, because it looks like it worked.
--
-- Seeded per organisation for the same reason the clinical schemas are: making
-- \`org_id\` nullable would put an \`or org_id is null\` branch into every RLS
-- policy on these tables.

begin;

alter table public.tools drop constraint if exists tools_origin_check;
alter table public.tools
  add constraint tools_origin_check check (origin in ('console', 'push', 'vendor'));

comment on column public.tools.origin is
  'console = made here. push = arrived from a repository via the CLI. vendor = a tool this product ships, editable nowhere.';

create or replace function public.seed_clinical_tools(p_org_id uuid)
returns integer
language plpgsql
set search_path = public
as $$
declare
  v_added integer := 0;
  v_tool  uuid;
  r       record;
begin
  for r in
    select * from (values
${rows}
    ) as t(id, name, description, schema, checksum, source, timeout_seconds)
  loop
    -- Derived from the organisation and the tool's authored id, so re-running
    -- inserts nothing twice and a rename stays the same row.
    v_tool := md5(p_org_id::text || ':vokoo-tool:' || r.id::text)::uuid;

    insert into public.tools (id, org_id, name, kind, description, schema, origin, locked, current_version)
    values (v_tool, p_org_id, r.name, 'function', r.description, r.schema, 'vendor', true, 1)
    on conflict (id) do nothing;

    if found then
      insert into public.tool_versions (org_id, tool_id, version, checksum, source, snapshot)
      values (
        p_org_id, v_tool, 1, r.checksum, r.source,
        jsonb_build_object(
          'name', r.name, 'description', r.description,
          'schema', r.schema, 'timeoutSeconds', r.timeout_seconds
        )
      )
      on conflict (tool_id, version) do nothing;
      v_added := v_added + 1;
    end if;
  end loop;

  return v_added;
end;
$$;

revoke all on function public.seed_clinical_tools(uuid) from public;
grant execute on function public.seed_clinical_tools(uuid) to service_role;

select public.seed_clinical_tools(id) from public.organizations;

create or replace function public.seed_clinical_tools_on_new_org()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.seed_clinical_tools(new.id);
  return new;
end;
$$;

drop trigger if exists organizations_seed_clinical_tools on public.organizations;
create trigger organizations_seed_clinical_tools
  after insert on public.organizations
  for each row execute function public.seed_clinical_tools_on_new_org();

commit;
`;

if (process.argv.includes("--check")) {
    const existing = readdirSync(join(ROOT, "supabase/migrations")).find((f) => f.includes("clinical_tools"));
    if (!existing) { process.stderr.write("no clinical tools migration committed yet\n"); process.exit(1); }
    const on_disk = readFileSync(join(ROOT, "supabase/migrations", existing), "utf8");
    if (on_disk !== sql) {
        process.stderr.write(`${existing} is out of date with packages/clinical-tools/src\n`);
        process.exit(1);
    }
    process.stderr.write("clinical tools migration is up to date\n");
} else {
    const [num, slug] = process.argv.slice(2);
    if (!/^\d{4}$/.test(num ?? "")) throw new Error("usage: seed-clinical-tools.mjs <NNNN> <slug>");
    const out = join(ROOT, "supabase/migrations", `${num}_${slug ?? "clinical_tools"}.sql`);
    if (existsSync(out)) throw new Error(`${basename(out)} exists — migrations are history, pick the next number`);
    writeFileSync(out, sql);
    for (const t of tools) process.stderr.write(`  ${t.name.padEnd(20)} ${t.file.padEnd(24)} ${t.checksum.slice(0, 19)}…\n`);
    process.stderr.write(`\nwrote ${out}\n`);
}
